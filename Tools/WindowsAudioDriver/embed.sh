#!/bin/bash
# Regenerates Sources/cakedlib/Windows/WindowsAudioDriverBinaries.swift from the files in arm64/ and amd64/ (see README.md).
set -euo pipefail

cd "$(dirname "$0")"

OUT=../../Sources/cakedlib/Windows/WindowsAudioDriverBinaries.swift

b64() {
	base64 < "$1/$2" | tr -d '\r\n'
}

package() {
	local dir=$1 name=$2 doc=$3

	echo "	/// $doc"
	echo "	static let $name = Package("
	echo '		sys: Data(base64Encoded: "'"$(b64 "$dir" viosnd.sys)"'")!,'
	echo '		inf: Data(base64Encoded: "'"$(b64 "$dir" viosnd.inf)"'")!,'
	echo '		cat: Data(base64Encoded: "'"$(b64 "$dir" viosnd.cat)"'")!,'
	echo '		certificate: Data(base64Encoded: "'"$(b64 "$dir" caker-audio-test-signing.cer)"'")!)'
}

{
	echo '// Generated by Tools/WindowsAudioDriver/embed.sh, do not edit.'
	echo
	echo 'import Foundation'
	echo
	echo '/// The virtio sound driver (viosnd) the Windows installation media carries: Windows has no virtio-snd driver and virtio-win'"'"'s'
	echo '/// ISO has none either. It is the BSD-licensed driver of https://github.com/317764920/viosnd with one change (an INF model'
	echo '/// line that gives Virtualization.framework'"'"'s sound device, PCI subsystem id 0x0059, a playback-only endpoint, since'
	echo '/// caker gives it no input stream). One build per guest architecture, each test-signed with its own certificate'
	echo '/// (see Tools/WindowsAudioDriver/README.md).'
	echo 'enum WindowsAudioDriverBinaries {'
	echo '	struct Package {'
	echo '		let sys: Data'
	echo '		let inf: Data'
	echo '		let cat: Data'
	echo '		/// The public half of the certificate that signed the driver, trusted by the installed system (the private key was not kept).'
	echo '		let certificate: Data'
	echo '	}'
	echo
	package arm64 arm64 'The ARM64 build (Apple silicon guests).'
	echo
	package amd64 amd64 'The x64 build (Intel guests).'
	echo
	echo '	static func package(for architecture: WindowsArchitecture) -> Package {'
	echo '		switch architecture {'
	echo '		case .arm64: return self.arm64'
	echo '		case .amd64: return self.amd64'
	echo '		}'
	echo '	}'
	echo '}'
} > "$OUT"

echo "Wrote $OUT"
