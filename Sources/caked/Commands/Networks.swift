	// MARK: - Network start command
	struct Start: ParsableCommand {
		static let configuration = NetworkStartOptions.configuration

		@OptionGroup(title: String(localized: "Global options"))
		var common: CommonOptions

		@Flag(help: ArgumentHelp(String(localized: "Forked command"), visibility: .hidden))
		public var fork: Bool = false

		@Argument(help: ArgumentHelp(String(localized: "Network name"), discussion: String(localized: "The name for network")))
		var name: String? = nil

		@Flag(name: .shortAndLong, help: ArgumentHelp(String(localized: "Start all networks")))
		public var all: Bool = false

		mutating func validate() throws {
			Logger.setLevel(self.common.logLevel)

			if name != nil && all {
				throw ValidationError("You can only specify one of <name> or --all")
			}

			if name == nil && all == false {
				throw ValidationError("You must specify one of <name> or --all")
			}

			if self.fork && self.all {
				throw ValidationError("You cannot specify --fork with --all")
			}

			#if USE_SETUID
				if self.fork {
					// A setuid-root caked launched by SudoCaked takes root as its real uid too, as sudo would have
					SudoCaked.becomeRootIfRequested()
				}
			#endif

			if let name {
				_ = try NetworksWrapper.validateNetwork(networkName: name, runMode: self.common.runMode)

				guard try NetworksWrapper.isRunningNetwork(networkName: name, runMode: self.common.runMode) == false else {
					throw ValidationError(String(localized: "Network \(name) is already running"))
				}
			}
		}

		func run() throws {
			if all {
				Logger.appendNewLine(self.common.format.render(NetworkStarter.startAll(runMode: self.common.runMode)))
			} else if let name {
				Logger.appendNewLine(self.common.format.render(NetworkStarter.start(options: try Networks.VMNetOptions(networkName: name, runMode: self.common.runMode), fork: self.fork, runMode: self.common.runMode)))
			}
		}
	}

