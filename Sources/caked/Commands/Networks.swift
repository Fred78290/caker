	// MARK: - Network imdsRedirect command
	/// Installs/removes the `pf` address-alias redirect that makes the AWS-style
	/// `169.254.169.254` address reach the real IMDS gateway (see `PFRedirect`). Invoked as
	/// a short-lived, separately-privileged helper via `SudoCaked` from `IMDSCoordinator` —
	/// nothing about the daemon itself runs as root.
	struct ImdsRedirect: ParsableCommand {
		static let configuration = CommandConfiguration(abstract: String(localized: "Manage the IMDS pf address-alias redirect"), shouldDisplay: false)

		@OptionGroup(title: String(localized: "Global options"))
		var common: CommonOptions

		@Flag(help: .hidden)
		var disable: Bool = false

		@Option(name: [.customLong("external-address")], help: .hidden)
		var externalAddress: String = IMDSNetworkInterface.awsCompatAddress

		@Option(name: [.customLong("internal-address")], help: .hidden)
		var internalAddress: String = IMDSServer.bindAddress

		@Option(name: [.customLong("internal-port")], help: .hidden)
		var internalPort: Int = 0

		func validate() throws {
			Logger.setLevel(self.common.logLevel)

			#if USE_SETUID
				// A setuid-root caked launched by SudoCaked takes root as its real uid too, as sudo would have
				SudoCaked.becomeRootIfRequested()
			#endif

			if geteuid() != 0 {
				throw ValidationError(String(localized: "This command must be run as root not as user \(geteuid())"))
			}

			if self.disable == false && self.internalPort == 0 {
				throw ValidationError(String(localized: "--internal-port is required"))
			}
		}

		func run() throws {
			if self.disable {
				try PFRedirect.disableAddressAlias()
			} else {
				try PFRedirect.enableAddressAlias(externalAddress: self.externalAddress, targetAddress: self.internalAddress, targetPort: self.internalPort)
			}
		}
	}

	// MARK: - Network stop command
	struct Stop: ParsableCommand {
		static let configuration = NetworkStopOptions.configuration

		@OptionGroup(title: String(localized: "Global options"))
		var common: CommonOptions

		@Argument(help: ArgumentHelp(String(localized: "network name"), discussion: String(localized: "network to stop, e.g., \"en0\" or \"shared\"")))
		var networkName: String? = nil

		@Flag(name: .shortAndLong, help: ArgumentHelp(String(localized: "Stop all networks")))
		public var all: Bool = false

		func validate() throws {
			Logger.setLevel(self.common.logLevel)

			if networkName != nil && all {
				throw ValidationError(String(localized: "You can only specify one of --network --all"))
			}

			if let networkName, all == false {
				guard try NetworksWrapper.validateNetwork(networkName: networkName, runMode: self.common.runMode).active == 0 else {
					throw ValidationError(String(localized: "Network \(networkName) is currently in use by one or more virtual machines"))
				}
			}
		}

		func run() throws {
			if all {
				Logger.appendNewLine(self.common.format.render(NetworksWrapper.stopAll(runMode: self.common.runMode)))
			} else if let networkName {
				Logger.appendNewLine(self.common.format.render(NetworksWrapper.stop(networkName: networkName, checkIfUsed: true, runMode: self.common.runMode)))
			} else {
				throw ValidationError(String(localized: "No network name provided"))
			}
		}
	}

