	public struct VMNetOptions: ParsableArguments {
		@Flag(help: .private)
		public var debug: Bool = false

		@Option(name: [.customLong("fd")], help: ArgumentHelp(String(localized: "Use file descriptor for VMNet")))
		public var vmfd: Int? = nil

		@Option(name: [.customLong("socket-group")], help: ArgumentHelp(String(localized: "socket group name")))
		public var socketGroup: String = "staff"

		@Option(name: [.customLong("mode")], help: ArgumentHelp(String(localized: "vmnet mode")))
		public var mode = VMNetMode.bridged

		@Option(name: [.customLong("interface")], help: ArgumentHelp(String(localized: "interface") + "\n", discussion: String(localized: "interface used for --vmnet=bridged, e.g., \"en0\"")))
		public var networkName: String = String.empty

		@Option(
			name: [.customLong("mac-address")],
			help: ArgumentHelp(String(localized: "Mac Address of network interface") + "\n", discussion: String(localized: "Mac address configured for VM network interface, autogenerated if not specified"), valueName: "mac"))
		public var macAddress: String = VZMACAddress.randomLocallyAdministered().string

		@Option(name: [.customLong("gateway")], help: ArgumentHelp(String(localized: "IP gateway") + "\n", discussion: String(localized: "gateway used for --vmnet=(host|shared), e.g., \"192.168.105.1\" (default: decided by macOS)")))
		public var gateway: String? = nil

		@Option(name: [.customLong("dhcp-end")], help: ArgumentHelp(String(localized: "end of the DHCP range") + "\n"))
		public var dhcpEnd: String? = nil

		@Option(help: ArgumentHelp(String(localized: "DHCP lease time in seconds")))
		public var dhcpLease: Int32? = nil

		@Option(name: [.customLong("netmask")], help: ArgumentHelp(String(localized: "Subnet mask") + "\n", discussion: String(localized: "requires --gateway to be specified")))
		public var subnetMask = "255.255.255.0"

		@Option(name: [.customLong("interface-id")], help: ArgumentHelp(String(localized: "VMNET interface ID") + "\n", discussion: String(localized: "randomly generated if not specified")))
		public var interfaceID = UUID().uuidString

		@Option(name: [.customLong("nat66-prefix")], help: ArgumentHelp(String(localized: "The IPv6 prefix to use with shared mode")))
		public var nat66Prefix: String? = nil

		//@Option(name: [.customLong("pidfile")], help: ArgumentHelp(String(localized: "save pid to PIDFILE")))
		//public var pidFile: String? = nil

		//@Argument(help: ArgumentHelp(String(localized: "socket path")))
		//public var socketPath: String? = nil

		@Flag(name: [.customLong("dns")], help: ArgumentHelp(String(localized: "Enable DNS")))
		public var dns: Bool = false

		#if !USE_IMDS_COORDINATOR_IN_SERVICE
			@Flag(name: [.customLong("imds")], help: ArgumentHelp(String(localized: "Enable IMDS Coordinator, apply only if network is imds"), visibility: .hidden))
			public var imds: Bool = false

			@Option(
				name: [.customLong("imds-port")],
				help: ArgumentHelp(
					String(localized: "Unprivileged port IMDS listens on"),
					discussion:
						String(
							format: String(
								localized:
									"AWS-style instance metadata service for Linux VMs. Off by default — enable it via the \"AWS EC2 Metadata\" toggle in Caker's Advanced settings. Once enabled, bound on this ordinary, unprivileged port on the IMDS gateway (%@) — always reachable from guests there, no privilege required, including in sandboxed builds. Ignored when caked runs as root, since IMDS then binds the standard port 80 directly instead."
							), IMDSNetworkInterface.imdsGateway),
					visibility: .hidden))
			var imdsPort: Int = IMDSServer.internalBindPort
		#endif

		public init() {

		}

		func validate() throws {
			if let vmfd = self.vmfd {
				guard fcntl(Int32(vmfd), F_GETFD) != -1 || errno != EBADF else {
					throw ValidationError(String(localized: "File descriptor is not open"))
				}
			}

			if self.mode == .bridged {
				if self.networkName == String.empty {
					throw ValidationError(String(localized: "interface is required for bridged mode"))
				}

				if self.gateway != nil {
					throw ValidationError(String(localized: "gateway is not allowed for bridged mode"))
				}

				if self.dhcpEnd != nil {
					throw ValidationError(String(localized: "dhcp-end is not allowed for bridged mode"))
				}
			} else if let gateway = self.gateway {
				guard let gatewayAddr = IP.V4(gateway) else {
					throw ValidationError(String(localized: "gateway is not a valid IP address"))
				}

				guard let dhcpEnd = self.dhcpEnd else {
					throw ValidationError(String(localized: "dhcp-end is required for host/shared mode when gateway is specified"))
				}

				guard let dhcpEndAddr = IP.V4(dhcpEnd) else {
					throw ValidationError(String(localized: "dhcp-end is not a valid IP address"))
				}

				guard self.subnetMask.isValidNetmask() else {
					throw ValidationError(String(localized: "valid netmask is required for host/shared mode when gateway is specified"))
				}

				let cidr = self.subnetMask.netmaskToCidr()
				let network = IP.Block<IP.V4>(base: gatewayAddr, bits: UInt8(cidr)).network

				if network.contains(dhcpEndAddr) == false {
					throw ValidationError(String(localized: "dhcp-end is not in the same network as gateway"))
				}
			}
		}

	}

