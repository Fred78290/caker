import AppKit
import Foundation

/// Generates a small macOS application that starts one guest application of a VM, so it can live in the Dock, Spotlight
/// or Launchpad like any other: a `.app` whose executable is a shell script running `app run` of `cakectl` or `caked`. Its icon is the
/// application's, read from the guest's icon theme by the caller (`GuestApplications.icon(for:run:)`, a PNG or an SVG turned into an `.icns`),
/// and it shows no Dock icon while it runs: the windows
/// belong to the process it starts, which is the one showing the guest's windows.
public enum GuestApplicationLauncher {
	public static let bundleIdentifierPrefix = "com.aldunelabs.caker.guestapp"

	public static var defaultDirectory: URL {
		FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Applications", isDirectory: true)
	}

	/// What the launcher shows as its name and what the bundle is called: the application's name and its VM.
	public static func displayName(vm: String, application: GuestApplication) -> String {
		"\(application.name) (\(vm))"
	}

	/// A file name from a free text: a slash would move the bundle elsewhere and a colon is a slash for Finder.
	static func fileName(_ text: String) -> String {
		let cleaned = text.map { $0 == "/" || $0 == ":" || $0.isNewline ? "-" : String($0) }.joined().trimmingCharacters(in: .whitespaces)

		return cleaned.isEmpty || cleaned.hasPrefix(".") ? "App" + cleaned : cleaned
	}

	static func bundleIdentifier(vm: String, application: GuestApplication) -> String {
		func part(_ text: String, keeping extra: Character? = nil) -> String {
			String(text.unicodeScalars.map { $0.isASCII && (CharacterSet.alphanumerics.contains($0) || $0 == "-" || Character($0) == extra) ? Character($0) : "-" })
		}

		// The identifier of a desktop file is already a reverse-DNS name: its dots stay.
		return "\(self.bundleIdentifierPrefix).\(part(vm)).\(part(application.shortID, keeping: "."))"
	}

	/// The script the bundle runs. Every word is quoted: a VM name or an identifier is a user's text.
	static func script(tool: String, vm: String, application: GuestApplication, extraArguments: [String]) -> String {
		let words = [tool, "app", "run", vm, application.id, "--start", "--wait", "120"] + extraArguments

		return """
			#!/bin/sh
			# Generated by `app create-launcher`.
			exec \(words.map(GuestApplications.shellQuoted).joined(separator: " "))

			"""
	}

	/// Turns the guest's icon (PNG or SVG data) into an `.icns` file. False when the data isn't an image or `iconutil` fails:
	/// the launcher then simply has the generic icon.
	static func writeIcon(_ data: Data, to destination: URL) -> Bool {
		guard let image = NSImage(data: data), image.isValid, image.size.width > 0, image.size.height > 0 else {
			return false
		}

		let fileManager = FileManager.default
		let iconset = fileManager.temporaryDirectory.appendingPathComponent("caker-launcher-\(UUID().uuidString).iconset", isDirectory: true)

		defer { try? fileManager.removeItem(at: iconset) }

		do {
			try fileManager.createDirectory(at: iconset, withIntermediateDirectories: true)

			// iconutil's names: each size once at 1x and once as the 2x of half of it.
			let sizes: [(name: String, pixels: Int)] = [
				("icon_16x16", 16), ("icon_16x16@2x", 32), ("icon_32x32", 32), ("icon_32x32@2x", 64),
				("icon_128x128", 128), ("icon_128x128@2x", 256), ("icon_256x256", 256), ("icon_256x256@2x", 512),
				("icon_512x512", 512), ("icon_512x512@2x", 1024),
			]

			for size in sizes {
				guard let png = self.png(of: image, pixels: size.pixels) else {
					return false
				}

				try png.write(to: iconset.appendingPathComponent(size.name + ".png"))
			}

			let process = Process()

			process.executableURL = URL(fileURLWithPath: "/usr/bin/iconutil")
			process.arguments = ["-c", "icns", "-o", destination.path(percentEncoded: false), iconset.path(percentEncoded: false)]
			process.standardError = FileHandle.nullDevice
			process.standardOutput = FileHandle.nullDevice

			try process.run()
			process.waitUntilExit()

			return process.terminationStatus == 0
		} catch {
			return false
		}
	}

	/// The image fitted and centred in a transparent square of `pixels` side.
	private static func png(of image: NSImage, pixels: Int) -> Data? {
		guard let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: pixels, pixelsHigh: pixels, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0), let context = NSGraphicsContext(bitmapImageRep: bitmap) else {
			return nil
		}

		let side = CGFloat(pixels)
		let scale = min(side / image.size.width, side / image.size.height)
		let width = image.size.width * scale
		let height = image.size.height * scale

		NSGraphicsContext.saveGraphicsState()
		NSGraphicsContext.current = context
		context.imageInterpolation = .high
		image.draw(in: NSRect(x: (side - width) / 2, y: (side - height) / 2, width: width, height: height), from: .zero, operation: .sourceOver, fraction: 1)
		NSGraphicsContext.restoreGraphicsState()

		return bitmap.representation(using: .png, properties: [:])
	}

	/// Writes the bundle into `directory` and returns its URL. An existing bundle of the same name is an error unless `overwrite`.
	/// `tool` is the executable the script runs: `cakectl` (windows shown by it) or `caked` (a VM it starts shows its own); both have `app run <vm> <id> --start --wait`.
	/// `extraArguments` are connection options (`--connect`, `--disable-tls`...) the script passes to the tool: never a password,
	/// which would end in a readable file.
	@discardableResult
	public static func create(vm: String, application: GuestApplication, tool: URL, extraArguments: [String] = [], in directory: URL = GuestApplicationLauncher.defaultDirectory, overwrite: Bool = false, icon: Data? = nil) throws -> URL {
		// The identifier comes from the guest: it ends in a script and in the bundle identifier.
		guard GuestApplications.isValidIdentifier(application.id) else {
			throw GuestApplications.Failure.invalidIdentifier(application.id)
		}

		let fileManager = FileManager.default
		let name = self.displayName(vm: vm, application: application)
		let bundle = directory.appendingPathComponent(self.fileName(name) + ".app", isDirectory: true)

		if fileManager.fileExists(atPath: bundle.path(percentEncoded: false)) {
			guard overwrite else {
				throw ServiceError(String(format: String(localized: "%@ already exists"), bundle.path(percentEncoded: false)))
			}

			try fileManager.removeItem(at: bundle)
		}

		let contents = bundle.appendingPathComponent("Contents", isDirectory: true)
		let executableDirectory = contents.appendingPathComponent("MacOS", isDirectory: true)
		let executable = executableDirectory.appendingPathComponent("launcher")

		try fileManager.createDirectory(at: executableDirectory, withIntermediateDirectories: true)
		try fileManager.createDirectory(at: contents.appendingPathComponent("Resources", isDirectory: true), withIntermediateDirectories: true)

		let hasIcon = icon.map { self.writeIcon($0, to: contents.appendingPathComponent("Resources/launcher.icns")) } ?? false

		var plist: [String: Any] = [
			"CFBundleExecutable": "launcher",
			"CFBundleIdentifier": self.bundleIdentifier(vm: vm, application: application),
			"CFBundleName": name,
			"CFBundleDisplayName": name,
			"CFBundlePackageType": "APPL",
			"CFBundleShortVersionString": "1.0",
			"CFBundleVersion": "1",
			"LSMinimumSystemVersion": "15.0",
			// The launcher itself has no window: the process it runs shows the guest's.
			"LSUIElement": true,
		]

		if hasIcon {
			plist["CFBundleIconFile"] = "launcher"
		}

		try PropertyListSerialization.data(fromPropertyList: plist, format: .xml, options: 0).write(to: contents.appendingPathComponent("Info.plist"))
		try Data(self.script(tool: tool.path(percentEncoded: false), vm: vm, application: application, extraArguments: extraArguments).utf8).write(to: executable)
		try fileManager.setAttributes([.posixPermissions: 0o755], ofItemAtPath: executable.path(percentEncoded: false))

		return bundle
	}
}
